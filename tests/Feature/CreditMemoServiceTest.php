<?php

namespace Tests\Feature;

use App\Contracts\LLM\LanguageModelProvider;
use App\Models\ApplicationExtraction;
use App\Models\Assessment;
use App\Models\AssessmentRuleResult;
use App\Models\LoanApplication;
use App\Models\PolicyEdition;
use App\Services\CreditMemo\CreditMemoService;
use App\Services\Underwriting\UnderwritingCitationResolver;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Str;
use Mockery;
use RuntimeException;
use Tests\TestCase;

class CreditMemoServiceTest extends TestCase
{
    use RefreshDatabase;

    public function test_it_generates_grounded_credit_memo_using_code_supplied_values(): void
    {
        $assessment = $this->createAssessmentWithRules();

        $this->bindCitationResolver();

        $this->app->instance(
            LanguageModelProvider::class,
            new class implements LanguageModelProvider
            {
                public function generate(
                    string $systemPrompt,
                    string $userPrompt
                ): string {
                    return <<<'MEMO'
Application Summary
Application reference: {{REFERENCE}}
Policy edition: {{POLICY_EDITION}}
Requested amount: {{REQUESTED_AMOUNT}}
Requested tenor months: {{TENOR_MONTHS}}
Net monthly income: {{NET_MONTHLY_INCOME}}
Existing monthly obligations: {{MONTHLY_OBLIGATIONS}}
Bureau score: {{BUREAU_SCORE}}

Affordability and Eligibility Assessment
Annual rate: {{ANNUAL_RATE}} [{{CITATION_PRICING}}; {{CITATION_PRODUCT_PRICING}}]
Monthly installment: {{MONTHLY_INSTALLMENT}} [{{CITATION_INSTALLMENT}}]
DBR percentage: {{DBR}} [{{CITATION_DBR}}]
Maximum eligible amount: {{MAX_ELIGIBLE_AMOUNT}} [{{CITATION_MAX_ELIGIBLE}}]

Policy-Grounded Recommendation
Recommendation: {{RECOMMENDATION}}
Recommended amount: {{RECOMMENDED_AMOUNT}}

Human Approval Requirement
The assessment remains pending human approval and no loan offer may be issued until an authorized credit officer approves it within their authority.
MEMO;
                }
            }
        );

        $service = app(CreditMemoService::class);

        $memo = $service->generate($assessment);

        $this->assertSame(
            'draft',
            $memo->status
        );

        $this->assertSame(
            $assessment->id,
            $memo->assessment_id
        );

        $this->assertStringContainsString(
            'APP-TEST',
            $memo->summary
        );

        $this->assertStringContainsString(
            '300000.00',
            $memo->summary
        );

        $this->assertStringContainsString(
            '24.00',
            $memo->summary
        );

        $this->assertStringContainsString(
            '8630.39',
            $memo->summary
        );

        $this->assertStringContainsString(
            '42.10',
            $memo->summary
        );

        $this->assertStringContainsString(
            'Credit Policy 2025 — CP-4.1',
            $memo->summary
        );

        $this->assertStringContainsString(
            'Pricing Table — PRICING',
            $memo->summary
        );

        $this->assertStringNotContainsString(
            '{{',
            $memo->summary
        );

        $this->assertContains(
            'Credit Policy 2025 — CP-4.2',
            $memo->citations
        );

        $this->assertContains(
            'Credit Policy 2025 — CP-4.3',
            $memo->citations
        );

        $this->assertContains(
            'Personal Loan Product Sheet — PS-4',
            $memo->citations
        );

        $this->assertDatabaseHas(
            'credit_memos',
            [
                'assessment_id' => $assessment->id,
                'status' => 'draft',
            ]
        );
    }

    public function test_it_rejects_numbers_generated_directly_by_language_model(): void
    {
        $assessment = $this->createAssessmentWithRules();

        $this->bindCitationResolver();

        $this->app->instance(
            LanguageModelProvider::class,
            new class implements LanguageModelProvider
            {
                public function generate(
                    string $systemPrompt,
                    string $userPrompt
                ): string {
                    return <<<'MEMO'
Application Summary
Application reference: {{REFERENCE}}

The applicant should receive 999999 according to the assessment.

Human Approval Requirement
Pending human approval.
MEMO;
                }
            }
        );

        $service = app(CreditMemoService::class);

        $this->expectException(
            RuntimeException::class
        );

        $this->expectExceptionMessage(
            'Credit memo draft contains a number generated by the language model.'
        );

        $service->generate($assessment);
    }

    private function bindCitationResolver(): void
    {
        $resolver = Mockery::mock(
            UnderwritingCitationResolver::class
        );

        $resolver
            ->shouldReceive('resolveClause')
            ->with(
                Mockery::type(PolicyEdition::class),
                'CP-4',
                'CP-4.2'
            )
            ->andReturn(
                'Credit Policy 2025 — CP-4.2'
            );

        $resolver
            ->shouldReceive('resolveClause')
            ->with(
                Mockery::type(PolicyEdition::class),
                'CP-4',
                'CP-4.3'
            )
            ->andReturn(
                'Credit Policy 2025 — CP-4.3'
            );

        $resolver
            ->shouldReceive('resolveProduct')
            ->with('PS-4')
            ->andReturn(
                'Personal Loan Product Sheet — PS-4'
            );

        $this->app->instance(
            UnderwritingCitationResolver::class,
            $resolver
        );
    }

    private function createAssessmentWithRules(): Assessment
    {
        $edition = PolicyEdition::create([
            'code' => 'CP-2025',
            'name' => 'Credit Policy 2025',
            'effective_from' => '2025-03-01',
            'effective_to' => null,
            'status' => 'active',
        ]);

        $application = LoanApplication::create([
            'reference_code' => 'APP-TEST',
            'requested_amount' => 300000,
            'requested_tenor_months' => 60,
            'date_of_birth' => '1990-01-01',
            'application_date' => '2025-04-01',
            'status' => 'submitted',
            'policy_edition_id' => $edition->id,
        ]);

        ApplicationExtraction::create([
            'loan_application_id' => $application->id,
            'net_monthly_income' => 30000,
            'existing_monthly_obligations' => 4000,
            'employment_start_date' => '2023-01-01',
            'bureau_score' => 712,
            'pricing_segment' => 'standard',
            'status' => 'completed',
        ]);

        $assessment = Assessment::create([
            'loan_application_id' => $application->id,
            'policy_edition_id' => $edition->id,
            'annual_rate_percent' => 24,
            'monthly_installment' => 8630.39,
            'debt_burden_ratio' => 42.10,
            'maximum_eligible_amount' => 330000,
            'recommendation' => 'eligible',
            'recommended_amount' => 300000,
            'approval_required_from' => null,
            'status' => 'pending_approval',
            'run_id' => (string) Str::uuid(),
        ]);

        $rules = [
            [
                'code' => 'dbr',
                'name' => 'Debt Burden Ratio',
                'citation' => 'Credit Policy 2025 — CP-4.1',
            ],
            [
                'code' => 'minimum_income',
                'name' => 'Minimum Net Monthly Income',
                'citation' => 'Credit Policy 2025 — CP-3.3',
            ],
            [
                'code' => 'employment_duration',
                'name' => 'Employment Duration',
                'citation' => 'Credit Policy 2025 — CP-3.2',
            ],
            [
                'code' => 'bureau_score',
                'name' => 'Bureau Score',
                'citation' => 'Credit Policy 2025 — CP-3.6',
            ],
            [
                'code' => 'age_at_maturity',
                'name' => 'Age at Maturity',
                'citation' => 'Credit Policy 2025 — CP-3.5',
            ],
            [
                'code' => 'tenor',
                'name' => 'Requested Tenor',
                'citation' => 'Personal Loan Product Sheet — PS-3',
            ],
            [
                'code' => 'amount',
                'name' => 'Requested Amount',
                'citation' => 'Personal Loan Product Sheet — PS-3',
            ],
        ];

        foreach ($rules as $rule) {
            AssessmentRuleResult::create([
                'assessment_id' => $assessment->id,
                'rule_code' => $rule['code'],
                'rule_name' => $rule['name'],
                'result' => 'pass',
                'reason' => 'Rule passed.',
                'citation' => $rule['citation'],
            ]);
        }

        return $assessment->fresh([
            'loanApplication.extraction',
            'policyEdition',
            'ruleResults',
        ]);
    }
}
